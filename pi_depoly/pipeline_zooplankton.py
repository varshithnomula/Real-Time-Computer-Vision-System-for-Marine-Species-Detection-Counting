# --- CONFIGURATION ---
YOLO_WEIGHTS = './yolo_best.pt'
CLASSIFIER_WEIGHTS = './mobilenet_v3_small_finetuned_best.pth'
CLASS_NAMES = sorted(classes)
IMG_SIZE_YOLO = 640
IMG_SIZE_CLS = 128
DEVICE ='cpu'

# --- LOAD MODELS ---
detector = YOLO(YOLO_WEIGHTS)

import torchvision.models as models

# Load the checkpoint first to determine the number of classes it was trained on
checkpoint = torch.load(CLASSIFIER_WEIGHTS, map_location=DEVICE)
state_dict = checkpoint['model_state_dict'] if 'model_state_dict' in checkpoint else checkpoint

# Extract the number of classes from the final layer weights (95 in this case)
num_checkpoint_classes = state_dict['classifier.3.weight'].shape[0]
print(f"Detected {num_checkpoint_classes} classes in checkpoint. Adjusting model architecture...")

# Initialize model with the correct number of classes from the weights file
classifier = models.mobilenet_v3_small(num_classes=num_checkpoint_classes)

# Load the state dict
classifier.load_state_dict(state_dict)

classifier.to(DEVICE)
classifier.eval()
print("MobileNet classifier loaded successfully.")

# Classification preprocessing
preprocess = transforms.Compose([
    transforms.Resize((IMG_SIZE_CLS, IMG_SIZE_CLS)),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
])

def run_inference(image_path, output_dir='inference_results'):
    os.makedirs(output_dir, exist_ok=True)
    img_orig = cv2.imread(image_path)
    if img_orig is None: return "Image not found"

    h0, w0 = img_orig.shape[:2]
    results_data = []

    # 1. YOLO Detection
    yolo_results = detector.predict(img_orig, imgsz=IMG_SIZE_YOLO, conf=0.25, verbose=False)

    annotated_img = img_orig.copy()

    for box in yolo_results[0].boxes:
        # Get coordinates
        x1, y1, x2, y2 = map(int, box.xyxy[0])

        # 2. Crop and Prepare for Classification
        crop = img_orig[max(0, y1):min(h0, y2), max(0, x1):min(w0, x2)]
        if crop.size == 0: continue

        crop_pil = PILImage.fromarray(cv2.cvtColor(crop, cv2.COLOR_BGR2RGB))
        input_tensor = preprocess(crop_pil).unsqueeze(0).to(DEVICE)

        # 3. MobileNet Classification
        with torch.no_grad():
            output = classifier(input_tensor)
            prob = torch.nn.functional.softmax(output[0], dim=0)
            conf, pred_idx = torch.max(prob, dim=0)
            label = CLASS_NAMES[pred_idx.item()]
            confidence = conf.item()

        # 4. Annotate Image
        cv2.rectangle(annotated_img, (x1, y1), (x2, y2), (0, 255, 0), 2)
        cv2.putText(annotated_img, f"{label} {confidence:.2f}", (x1, y1-10),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 2)

        results_data.append({"species": label, "confidence": confidence, "x1": x1, "y1": y1, "x2": x2, "y2": y2})

    # 5. Save Results
    base_name = os.path.basename(image_path).split('.')[0]
    cv2.imwrite(f"{output_dir}/{base_name}_annotated.jpg", annotated_img)

    df = pd.DataFrame(results_data)
    df.to_csv(f"{output_dir}/{base_name}_report.csv", index=False)

    # Summary counts
    if not df.empty:
        print(f"\nSummary for {base_name}:")
        print(df['species'].value_counts())

    return df

