def create_charts(df):
    if df.empty:
        return None

    counts = df['species'].value_counts()

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))
    fig.suptitle('Species Distribution', fontsize=14, fontweight='bold')

    # Bar chart
    counts.plot(kind='bar', ax=ax1, color='steelblue')
    ax1.set_title('Species Count')
    ax1.set_xlabel('Species')
    ax1.set_ylabel('Count')
    ax1.tick_params(axis='x', rotation=45)

    # Pie chart
    ax2.pie(counts.values, labels=counts.index, autopct='%1.1f%%', startangle=90)
    ax2.set_title('Species Distribution %')

    plt.tight_layout()

    # Convert to image for Gradio
    buf = io.BytesIO()
    plt.savefig(buf, format='png', dpi=120, bbox_inches='tight')
    buf.seek(0)
    chart_img = PILImage.open(buf)
    plt.close()
    return chart_img


def compare_samples(folder_a, folder_b):
    def count_folder(folder):
        counts = {}
        if folder is None:
            folder = ''
        folder = folder.strip().strip('"').strip("'")
        folder = os.path.normpath(folder)
        print(f"Searching in folder: {folder}")
        if not os.path.isdir(folder):
            print(f"  Folder not found: {folder}")
            return counts

        image_extensions = ('*.jpg', '*.jpeg', '*.png', '*.JPG', '*.JPEG', '*.PNG')
        files = []
        for ext in image_extensions:
            files.extend(glob.glob(os.path.join(folder, ext)))
        print(f"Found {len(files)} image files")
        
        for f in files:
            print(f"  Processing: {f}")
            df = run_inference(f, output_dir='comparison_temp')
            if isinstance(df, str):
                print(f"    Error: {df}")
                continue
            if isinstance(df, pd.DataFrame) and not df.empty:
                print(f"    Detected {len(df)} objects")
                for sp in df['species']:
                    counts[sp] = counts.get(sp, 0) + 1
            else:
                print(f"    No objects detected")
        return counts

    print("Processing Sample A...")
    counts_a = count_folder(folder_a)
    print(f"Found {len(counts_a)} unique species in Sample A")
    print("Processing Sample B...")
    counts_b = count_folder(folder_b)
    print(f"Found {len(counts_b)} unique species in Sample B")

    # Build comparison dataframe
    all_species = sorted(set(list(counts_a.keys()) + list(counts_b.keys())))
    print(f"Total unique species: {len(all_species)}")
    
    rows = []
    for sp in all_species:
        a = counts_a.get(sp, 0)
        b = counts_b.get(sp, 0)
        rows.append({
            'Species': sp,
            'Sample A': a,
            'Sample B': b,
            'Difference': b - a,
            'Change': '▲ Increased' if b > a else ('▼ Decreased' if b < a else '— Same')
        })

    if rows:
        comparison_df = pd.DataFrame(rows).sort_values('Difference', key=abs, ascending=False)
    else:
        comparison_df = pd.DataFrame(columns=['Species', 'Sample A', 'Sample B', 'Difference', 'Change'])
    
    comparison_df.to_csv('comparison_report.csv', index=False)
    print(f"Comparison report saved. Shape: {comparison_df.shape}")

    # Create comparison chart
    if len(all_species) == 0:
        print("No species detected in either sample - creating empty chart")
        fig, ax = plt.subplots(figsize=(14, 6))
        ax.text(0.5, 0.5, 'No species detected', ha='center', va='center', fontsize=16)
        ax.set_title('Sample A vs Sample B — Species Comparison')
    else:
        fig, ax = plt.subplots(figsize=(14, 6))
        x = range(len(all_species))
        width = 0.35
        ax.bar([i - width/2 for i in x], [counts_a.get(s, 0) for s in all_species],
               width, label='Sample A', color='steelblue')
        ax.bar([i + width/2 for i in x], [counts_b.get(s, 0) for s in all_species],
               width, label='Sample B', color='coral')
        ax.set_xticks(list(x))
        ax.set_xticklabels(all_species, rotation=45, ha='right', fontsize=8)
        ax.set_title('Sample A vs Sample B — Species Comparison')
        ax.set_ylabel('Count')
        ax.legend()
    
    plt.tight_layout()

    # Save chart to file instead of buffer
    chart_path = 'comparison_chart.png'
    plt.savefig(chart_path, format='png', dpi=120, bbox_inches='tight')
    plt.close()
    print(f"Chart saved to {chart_path}")

    return chart_path, comparison_df, 'comparison_report.csv'


def gradio_inference(input_img):
    temp_path = "gradio_input.jpg"
    input_img_bgr = cv2.cvtColor(input_img, cv2.COLOR_RGB2BGR)
    cv2.imwrite(temp_path, input_img_bgr)

    df = run_inference(temp_path, output_dir='gradio_results')

    if isinstance(df, str):
        return None, pd.DataFrame(), None, None

    annotated_path = 'gradio_results/gradio_input_annotated.jpg'
    output_img = cv2.cvtColor(cv2.imread(annotated_path), cv2.COLOR_BGR2RGB)

    summary = df['species'].value_counts().reset_index()
    summary.columns = ['Species', 'Count']

    charts = create_charts(df)
    report_csv = 'gradio_results/gradio_input_report.csv'

    return output_img, summary, charts, report_csv

