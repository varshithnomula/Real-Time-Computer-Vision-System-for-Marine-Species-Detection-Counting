def run_batch_inference(input_folder, output_folder='batch_results'):
    """Runs inference on every image in the specified folder."""
    image_extensions = ('*.jpg', '*.jpeg', '*.png')
    files_to_process = []
    for ext in image_extensions:
        files_to_process.extend(glob.glob(os.path.join(input_folder, ext)))

    print(f"Found {len(files_to_process)} images in {input_folder}. Starting batch processing...")

    all_dfs = []
    for img_path in tqdm(files_to_process):
        df = run_inference(img_path, output_dir=output_folder)
        if isinstance(df, pd.DataFrame):
            df['source_file'] = os.path.basename(img_path)
            all_dfs.append(df)

    if all_dfs:
        master_report = pd.concat(all_dfs, ignore_index=True)
        master_report.to_csv(f"{output_folder}/master_batch_report.csv", index=False)
        print(f"\nBatch processing complete. Summary report saved to {output_folder}/master_batch_report.csv")


